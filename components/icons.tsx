import type { SVGProps } from "react";

// The app's icon set. Local inline SVG rather than an icon package: this repo carries
// no UI dependencies at all, and the sixteen-odd glyphs below are the whole need.
// Geometry follows Lucide (24x24 box, 1.5 stroke, round caps/joins) so anything added
// later can be copied straight from there and will sit correctly beside these.
//
// All of them inherit `currentColor` and default to 1rem, so an icon takes the colour
// and cadence of the text it sits in. They are `aria-hidden` by default — an icon-only
// control must carry its own aria-label on the BUTTON, not on the glyph.

type IconProps = SVGProps<SVGSVGElement>;

function Icon({ className = "h-4 w-4", children, ...rest }: IconProps) {
  return (
    <svg
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={1.5}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={className}
      aria-hidden="true"
      {...rest}
    >
      {children}
    </svg>
  );
}

